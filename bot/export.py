"""Export backtest results for the static results site in docs/.

    python -m bot.run export                       # symbol from config.yaml
    python -m bot.run export --symbols AAPL SPY QQQ

Writes docs/data.js. The page loads it with a plain <script> tag rather than
fetch(), so docs/index.html also works when opened straight from disk.

Only prices and results are exported. No keys, no account data.
"""

from __future__ import annotations

import json
import logging
from dataclasses import replace
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from .backtest import FAST_GRID, SLOW_GRID, run_backtest
from .config import ROOT, Config
from .data import fetch_daily_bars

SITE_DIR = ROOT / "docs"
STARTING_CASH = 10_000.0

log = logging.getLogger(__name__)


def build_symbol_payload(bars: pd.DataFrame, cfg: Config) -> dict:
    # Round first, then backtest, so Python and the browser see identical
    # prices and the page's consistency check compares like with like.
    bars = bars[["open", "close"]].astype(float).round(4)

    configured = run_backtest(
        bars, cfg.fast_period, cfg.slow_period, cfg.slippage_bps, STARTING_CASH
    ).summary()

    sweep = []
    for fast in FAST_GRID:
        for slow in SLOW_GRID:
            if fast >= slow:
                continue
            s = run_backtest(bars, fast, slow, cfg.slippage_bps, STARTING_CASH).summary()
            sweep.append(
                {
                    "fast": fast,
                    "slow": slow,
                    "return_pct": s["strategy_return_pct"],
                    "trades": s["trades"],
                    "sharpe": s["sharpe"],
                }
            )

    return {
        "dates": [d.strftime("%Y-%m-%d") for d in bars.index],
        "open": [float(x) for x in bars["open"]],
        "close": [float(x) for x in bars["close"]],
        # The page recomputes this pair in the browser and compares.
        "python_check": {
            "fast": cfg.fast_period,
            "slow": cfg.slow_period,
            **configured,
        },
        "sweep": sweep,
    }


def build_payload(bars_by_symbol: dict[str, pd.DataFrame], cfg: Config) -> dict:
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "default_symbol": next(iter(bars_by_symbol)),
        "fast": cfg.fast_period,
        "slow": cfg.slow_period,
        "slippage_bps": cfg.slippage_bps,
        "starting_cash": STARTING_CASH,
        "fast_grid": list(FAST_GRID),
        "slow_grid": list(SLOW_GRID),
        "symbols": {
            sym: build_symbol_payload(bars, cfg) for sym, bars in bars_by_symbol.items()
        },
    }


def write_site_data(payload: dict, out_dir: Path = SITE_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "data.js"
    body = json.dumps(payload, separators=(",", ":"), allow_nan=False)
    path.write_text(
        "// Generated by `python -m bot.run export`. Do not edit by hand.\n"
        f"window.BACKTEST_DATA = {body};\n"
    )
    return path


def export_site(cfg: Config, symbols: list[str], lookback_days: int = 1500) -> Path:
    bars_by_symbol: dict[str, pd.DataFrame] = {}
    for raw in symbols:
        sym_cfg = replace(cfg, symbol=raw.upper())
        log.info("Fetching %s", sym_cfg.symbol)
        bars_by_symbol[sym_cfg.symbol] = fetch_daily_bars(sym_cfg, lookback_days=lookback_days)
    return write_site_data(build_payload(bars_by_symbol, cfg))
